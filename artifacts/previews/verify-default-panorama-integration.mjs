import {chromium} from 'file:///C:/Users/user/Desktop/holoseogi-counsel/node_modules/playwright-core/index.mjs'
const browser=await chromium.launch({headless:true,executablePath:'C:/Users/user/AppData/Local/ms-playwright/chromium-1243/chrome-win64/chrome.exe'})
const url='http://127.0.0.1:5186/artifacts/previews/aquarium-default-integration.html'
try{
 for(const width of [320,390,1000]){
  const page=await browser.newPage({viewport:{width,height:844},hasTouch:true,deviceScaleFactor:2})
  const errors=[],remote=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.route('**/*.supabase.co/**',route=>{remote.push(route.request().url());return route.abort()})
  await page.goto(url)
  await page.getByAltText('맑은 물빛',{exact:true}).waitFor()
  await page.waitForTimeout(700)
  const read=async()=>JSON.parse(await page.getByTestId('saved-preview-items').textContent())
  const glass=page.getByTestId('aquarium-glass'),bounds=await glass.boundingBox()
  const original=await read()
  await page.getByRole('button',{name:'왼쪽 수조 보기'}).click()
  await page.waitForFunction(()=>+document.querySelector('[data-testid="aquarium-glass"]').dataset.view<.001)
  if(JSON.stringify(await read())!==JSON.stringify(original))throw Error('Panning changed saved items')
  await page.screenshot({path:`artifacts/previews/default-integration-${width}-left.png`})
  await page.getByRole('button',{name:'살구 불가사리 선택'}).focus()
  await page.getByRole('button',{name:'살구 불가사리 선택'}).press('Enter')
  await page.getByRole('button',{name:'시계 방향 15도 회전',exact:true}).waitFor()
  await page.waitForFunction(()=>Math.abs(+document.querySelector('[data-testid="aquarium-glass"]').dataset.view-1)<.001)
  if(await page.getByRole('group',{name:'수조 둘러보기'}).count())throw Error('Pan controls overlap decoration editor')
  const item=(await read()).find(item=>item.species_id==='apricot-starfish')
  await page.getByRole('button',{name:'시계 방향 15도 회전',exact:true}).click()
  await page.waitForFunction(()=>JSON.parse(document.querySelector('[data-testid="saved-preview-items"]').textContent).some(item=>item.species_id==='apricot-starfish'&&item.rotation===45))
  await page.getByRole('button',{name:'크기 키우기',exact:true}).click()
  await page.waitForFunction(()=>JSON.parse(document.querySelector('[data-testid="saved-preview-items"]').textContent).some(item=>item.species_id==='apricot-starfish'&&item.scale===1.3))
  const transformed=(await read()).find(item=>item.species_id==='apricot-starfish')
  const centered=await page.evaluate(async({item,transformed,width,height})=>{
   const {decorationGeometry}=await import('/src/features/aquarium/decoration-geometry.ts')
   const catalog=(await import('/supabase/catalog/catalog.json')).default
   const species=catalog.collectible_species.find(s=>s.id==='apricot-starfish')
   const a=decorationGeometry({...item,species},width,height),b=decorationGeometry({...transformed,species},width,height)
   const center=(item,g)=>({x:g.margin+item.position_x*g.w+g.size/2,y:g.margin+item.position_y*g.h+g.size/2})
   return {before:center(item,a),after:center(transformed,b),size:b.size}
  },{item,transformed,width:bounds.width,height:bounds.height})
  if(Math.hypot(centered.before.x-centered.after.x,centered.before.y-centered.after.y)>.01)throw Error('Scale/rotation moved decoration center')
  await page.getByRole('button',{name:'개체 선택 닫기'}).click()
  await page.mouse.move(bounds.x+centered.after.x,bounds.y+centered.after.y)
  await page.mouse.down()
  await page.mouse.move(bounds.x+centered.after.x+30,bounds.y+centered.after.y-35,{steps:12})
  await page.mouse.up()
  await page.waitForFunction(before=>JSON.parse(document.querySelector('[data-testid="saved-preview-items"]').textContent).some(item=>item.species_id==='apricot-starfish'&&Math.abs(item.position_x-before)>.01),transformed.position_x)
  await page.screenshot({path:`artifacts/previews/default-integration-${width}-editing.png`})
  const saved=await read()
  await page.getByRole('button',{name:'산호 테마',exact:true}).click()
  await page.getByAltText('산호 정원',{exact:true}).waitFor()
  await page.getByRole('button',{name:'개체 선택 닫기'}).click()
  if(!await page.getByRole('group',{name:'수조 둘러보기'}).count())throw Error('Coral theme is missing panorama controls')
  if(JSON.stringify(await read())!==JSON.stringify(saved))throw Error('Theme change modified placement')
  await page.screenshot({path:`artifacts/previews/default-integration-${width}-coral.png`})
  await page.getByRole('button',{name:'기본 테마',exact:true}).click()
  await page.getByAltText('맑은 물빛',{exact:true}).waitFor()
  if(JSON.stringify(await read())!==JSON.stringify(saved))throw Error('Returning to default modified placement')
  await page.getByRole('button',{name:'오른쪽 수조 보기'}).click()
  await page.waitForFunction(()=>+document.querySelector('[data-testid="aquarium-glass"]').dataset.view>1.999)
  await page.screenshot({path:`artifacts/previews/default-integration-${width}-right.png`})
  if(errors.length||remote.length)throw Error(JSON.stringify({errors,remote}))
  await page.getByRole('button',{name:'수조 이동 메뉴 최소화'}).click()
  const collapsed=page.getByRole('button',{name:'수조 이동 메뉴 펼치기'})
  if((await collapsed.boundingBox()).width<44)throw Error('Collapsed control too small')
  await collapsed.click()
  console.log({width,placementPreserved:true,rotation:true,scale:true,drag:true,coralPanorama:true,collapse:true,remoteRequests:remote.length})
  await page.close()
 }
}finally{await browser.close()}
