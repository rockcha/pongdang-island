import {build} from 'vite'
import {readFileSync,writeFileSync} from 'node:fs'
const result=await build({configFile:false,publicDir:false,logLevel:'silent',build:{write:false,minify:false,target:'es2022',lib:{entry:'src/features/arcade/billiards-replay.ts',formats:['es'],fileName:'billiards-replay'}}})
const output=Array.isArray(result)?result[0]:result
const code='// Generated by npm run billiards:engine. Do not edit.\n'+output.output.find(chunk=>chunk.type==='chunk').code
const path='supabase/functions/_shared/billiards-replay.js'
if(process.argv.includes('--check')){if(readFileSync(path,'utf8').replaceAll('\r\n','\n')!==code)throw Error('Billiards server engine is stale; run npm run billiards:engine')}
else writeFileSync(path,code)
