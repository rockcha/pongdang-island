import {build} from 'vite'
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs'
const result=await build({configFile:false,publicDir:false,logLevel:'silent',build:{write:false,minify:false,target:'es2022',lib:{entry:'src/features/arcade/brick-breaker-replay.ts',formats:['es'],fileName:'brick-replay'}}})
const output=Array.isArray(result)?result[0]:result
const code='// Generated by npm run arcade:engine. Do not edit.\n'+output.output.find(chunk=>chunk.type==='chunk').code
const path='supabase/functions/_shared/brick-replay.js'
if(process.argv.includes('--check')){if(readFileSync(path,'utf8').replaceAll('\r\n','\n')!==code)throw Error('Brick server engine is stale; run npm run arcade:engine')}
else{mkdirSync('supabase/functions/_shared',{recursive:true});writeFileSync(path,code)}
