import {readFileSync,writeFileSync,existsSync} from 'node:fs'
import {dirname,relative,resolve,sep} from 'node:path'
const root='assets/references/mythic-sprites'
const read=path=>JSON.parse(readFileSync(path,'utf8').replace(/^\uFEFF/,''))
const sources=read(root+'/sources.json'),catalog=read('supabase/catalog/catalog.json')
const species=new Map(catalog.collectible_species.map(s=>[s.id,s])),entries=new Map()
const link=path=>relative(resolve(root),resolve(path)).split(sep).join('/')
for(const manifestPath of sources.manifests){
 const manifest=read(manifestPath),batch=dirname(manifestPath),registration=batch+'/registration.json'
 if(!existsSync(registration))throw Error('Missing registration: '+registration)
 const reports=read(registration)
 for(const e of manifest.entries){
  const s=species.get(e.id)
  if(!s||s.kind!=='fish'||s.rarity!=='mythic')throw Error('Not a catalog mythic creature: '+e.id)
  if(e.frames!==8||e.columns!==4||!e.prompt)throw Error('Missing eight-frame prompt: '+e.id)
  const image=batch+'/'+e.storage_path,source=batch+'/'+e.source
  for(const path of [image,source])if(!existsSync(path))throw Error('Missing reference: '+path)
  if(!reports.some(r=>r.id===e.id&&r.rawAudit?.bounds?.length===8))throw Error('Missing source-cell audit: '+e.id)
  entries.set(e.id,{name:s.name,image,manifestPath,registration})
 }
}
const rows=[...entries.values()].map(e=>`| ${e.name} | [최종 8프레임](${link(e.image)}) | [프롬프트·입력 역할](${link(e.manifestPath)}) · [원본 여백·위치 보정](${link(e.registration)}) |`)
const output='# 검수한 신화 스프라이트 참고\n\n<!-- Generated by scripts/build-mythic-reference-index.mjs; do not edit. -->\n\n[제작·검수 절차](README.md)를 먼저 읽는다. 아래 이미지는 동작과 여백을 참고하는 최종본이며, 같은 manifest의 실패 시안은 제외한다. 프롬프트·등록 기록에서는 해당 종 ID로 찾는다.\n\n| 개체 | 이미지 | 생성·검수 출처 |\n| --- | --- | --- |\n'+rows.join('\n')+'\n'
writeFileSync(root+'/index.md',output)
console.log(`Validated and indexed ${entries.size} mythic references`)
