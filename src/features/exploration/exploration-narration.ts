export const scorpionArrivalLines=[getMonster('sand-scorpion').arrival,...monsterArrivalVariants['sand-scorpion']]

export function drawNarration(lines:readonly string[],previous?:string|null,random=Math.random):string{
 const available=lines.filter(line=>line!==previous)
 const pool=available.length?available:lines
 return pool[Math.min(pool.length-1,Math.floor(random()*pool.length))]
}

export function monsterArrivalLines(id:MonsterId):readonly string[]{
 return [getMonster(id).arrival,...(monsterArrivalVariants[id]??[])]
}

export function drawMonsterArrival(id:MonsterId,previous?:string,random=Math.random):string{
 return drawNarration(monsterArrivalLines(id),previous,random)
}
