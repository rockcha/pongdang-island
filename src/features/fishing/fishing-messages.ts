// Hash each action independently for variety, while staying stable on animation
// frames and never consuming gameplay randomness.
function choose(pool: string[], seed: number, cycle: number) {
  const actionSeed = seed ^ Math.imul(cycle, 0x9e3779b9)
  const hash = Math.imul(actionSeed ^ (actionSeed >>> 16), 0x45d9f3b) >>> 0
  return pool[hash % pool.length]
}
export function fishingMessage(game: TensionGame): string {
  if (game.phase === 'waiting') return ''
  if (game.phase === 'won') return ''
  if (game.phase === 'lost') return choose(lost, game.seed, 0)
  const behavior = fishBehavior(game.time, game.seed, game.rarity)
  if (behavior.index === -1)
    return choose(
      game.time < fishingBiteSeconds(game.seed) * 0.6 ? approaching : nibbling,
      game.seed,
      0,
    )
  const pool =
    behavior.mood === 'surge'
      ? raritySurge[game.rarity]
      : behavior.mood === 'warning'
        ? warning
        : behavior.mood === 'recover'
          ? recover
          : calm
  return choose(pool, game.seed, Math.floor(behavior.index / 2))
}
