import {cleanup,fireEvent,render,screen,waitFor} from '@testing-library/react'
import {afterEach,beforeEach,expect,it,vi} from 'vitest'
import {AttendanceButton} from '@/features/attendance/attendance-button'
const {load,claim,refresh,success}=vi.hoisted(()=>({load:vi.fn(),claim:vi.fn(),refresh:vi.fn(),success:vi.fn()}))
vi.mock('@/components/auth-provider',()=>({useAuth:()=>({session:{user:{id:'attendee'}}})}))
vi.mock('@/features/gold/gold-provider',()=>({GoldIcon:()=> <img alt="" src="/gold.png"/>,useGold:()=>({refresh,busy:false,loading:false})}))
vi.mock('@/features/attendance/api',()=>({loadAttendance:load,claimAttendance:claim,attendanceError:()=> '다시 불러와주세요.'}))
vi.mock('sonner',()=>({toast:{success}}))
const pending={today:'2026-10-16',checkedIn:false,streak:6,currentDay:7,completedDays:6,sheetNumber:1,completedSheets:0,reset:false}
beforeEach(()=>{load.mockResolvedValue(pending);refresh.mockResolvedValue(undefined);claim.mockResolvedValue({...pending,checkedIn:true,streak:7,completedDays:7,replayed:false,reward:{gold:0,fuel:0,bait_id:'bait_first_greeting'}})})
afterEach(()=>{cleanup();vi.clearAllMocks()})
it('shows alternating fuel rewards and announces the actual fuel claim',async()=>{
 load.mockResolvedValue({...pending,currentDay:2,streak:1,completedDays:1})
 claim.mockResolvedValue({...pending,currentDay:2,checkedIn:true,streak:2,completedDays:2,replayed:false,reward:{gold:0,fuel:3,bait_id:null}})
 render(<AttendanceButton/>)
 fireEvent.click(await screen.findByRole('button',{name:'출석체크 · 오늘 출석 전'}))
 const button=await screen.findByRole('button',{name:'2일차 오늘 · 연료 3통'})
 await waitFor(()=>expect((button as HTMLButtonElement).disabled).toBe(false))
 expect(button.querySelector('img')?.getAttribute('src')).toBe('/app-icons/fuel-can.svg')
 fireEvent.click(button)
 await waitFor(()=>expect(success).toHaveBeenCalledWith('출석 완료! 연료 3통 획득'))
})
it('shows a brown pending dot, stamps today once and refreshes earned gold',async()=>{
 const view=render(<AttendanceButton/>)
 const button=await screen.findByRole('button',{name:'출석체크 · 오늘 출석 전'})
 expect(view.container.querySelector('[data-attendance-pending]')).toBeTruthy()
 fireEvent.click(button)
 await screen.findByRole('dialog')
 const sheet=screen.getByLabelText('28일 출석지')
 expect(sheet.children).toHaveLength(28)
 expect(sheet.classList.contains('grid-cols-7')).toBe(true)
 for(const day of [7,14,21])expect(sheet.children[day-1].getAttribute('aria-label')).toContain('소라의 첫인사')
 expect(sheet.children[27].getAttribute('aria-label')).toContain('별잠의 유혹')
 const attend=await screen.findByRole('button',{name:'7일차 오늘 · 소라의 첫인사'})
 await waitFor(()=>expect((attend as HTMLButtonElement).disabled).toBe(false))
 fireEvent.click(attend);fireEvent.click(attend)
 await screen.findByRole('button',{name:'7일차 출석 완료 · 소라의 첫인사'})
 expect(claim).toHaveBeenCalledExactlyOnceWith('2026-10-16')
 expect(success).toHaveBeenCalledTimes(1)
 expect(success).toHaveBeenCalledWith('출석 완료! 소라의 첫인사 1개 획득')
 expect(attend.querySelector('img')?.getAttribute('src')).toBe('/items/baits/conch-first-greeting.png')
 expect(attend.querySelector('img[src="/gold.png"],img[src="/app-icons/fuel.png"]')).toBeNull()
 expect(refresh).toHaveBeenCalled()
 expect(view.container.querySelector('[data-attendance-pending]')).toBeNull()
 expect(document.querySelector('[aria-label="7일차 출석 완료 · 소라의 첫인사"]')).toBeTruthy()
})
it('keeps completed reward boxes visible without offering a second claim',async()=>{
 load.mockResolvedValue({...pending,checkedIn:true,streak:28,currentDay:28,completedDays:28,completedSheets:1})
 render(<AttendanceButton/>)
 fireEvent.click(await screen.findByRole('button',{name:'출석체크 · 오늘 출석 완료'}))
 expect(await screen.findByRole('dialog',{name:'퐁당섬 출석체크'})).toBeTruthy()
 expect((screen.getByRole('button',{name:'28일차 출석 완료 · 별잠의 유혹'}) as HTMLButtonElement).disabled).toBe(true)
 expect(claim).not.toHaveBeenCalled()
})
it('shows errors without falsely stamping or announcing rewards',async()=>{
 claim.mockRejectedValue(new Error('offline'))
 const view=render(<AttendanceButton/>)
 fireEvent.click(await screen.findByRole('button',{name:'출석체크 · 오늘 출석 전'}))
 const button=await screen.findByRole('button',{name:'7일차 오늘 · 소라의 첫인사'})
 await waitFor(()=>expect((button as HTMLButtonElement).disabled).toBe(false))
 fireEvent.click(button)
 expect(await screen.findByRole('alert')).toBeTruthy()
 expect(success).not.toHaveBeenCalled()
 expect(view.container.querySelector('[data-attendance-pending]')).toBeTruthy()
})
