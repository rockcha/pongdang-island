import {act,cleanup,fireEvent,render,screen,waitFor,within} from '@testing-library/react'
import {afterEach,beforeEach,expect,it,vi} from 'vitest'
import {BeggingScreen} from '@/features/begging/begging-page'
import type {BeggingRequest} from '@/features/begging/api'
const toast=vi.hoisted(()=>({success:vi.fn(),error:vi.fn()}))
vi.mock('sonner',()=>({toast}))
vi.mock('@/features/profile/player-avatar',()=>({PlayerAvatar:({nickname}:{nickname:string})=><img alt={`${nickname}의 아바타`}/>}))
const post:BeggingRequest={id:'story',story:'새 낚싯대를 마련하고 싶어요.',goalGold:1000,receivedGold:0,status:'active',createdAt:'2026-10-25T16:00:00Z',closedAt:null,mine:false,owner:{id:'owner',nickname:'낚시퐁이',avatarPath:null},transferCount:0,donors:[]}
const service={loadBegging:vi.fn(),loadBeggingHistory:vi.fn(),loadBeggingDetail:vi.fn(),createBegging:vi.fn(),giveBegging:vi.fn(),closeBegging:vi.fn()}
beforeEach(()=>{vi.clearAllMocks();service.loadBegging.mockResolvedValue({items:[post],hasMore:false});service.loadBeggingHistory.mockResolvedValue({items:[],hasMore:false});service.loadBeggingDetail.mockResolvedValue({request:post,items:[],hasMore:false})})
afterEach(cleanup)
it('requires at least 100 gold and shows the 2 XP reward before sending exactly one request',async()=>{
 let resolve!:(value:unknown)=>void;service.giveBegging.mockImplementation(()=>new Promise(r=>{resolve=r}))
 render(<BeggingScreen owner="me" gold={1000} service={service}/>)
 fireEvent.click(await screen.findByRole('button',{name:/골드 보내기/}))
 const dialog=screen.getByRole('dialog');expect(within(dialog).getByText('+2 EXP')).toBeTruthy()
 fireEvent.change(within(dialog).getByLabelText('보낼 골드'),{target:{value:'99'}})
 expect(within(dialog).getByRole('button',{name:'100골드 이상 입력해주세요'}).hasAttribute('disabled')).toBe(true)
 expect(service.giveBegging).not.toHaveBeenCalled()
 fireEvent.change(within(dialog).getByLabelText('보낼 골드'),{target:{value:'100'}})
 const submit=within(dialog).getByRole('button',{name:'100골드 보내기'});fireEvent.click(submit);fireEvent.click(submit)
 expect(service.giveBegging).toHaveBeenCalledTimes(1)
 expect(service.giveBegging.mock.calls[0][0]).toMatchObject({requestId:'story',gold:100,operationId:expect.any(String)})
 await act(async()=>resolve({request:{...post,receivedGold:100,transferCount:1,donors:[{id:'receipt',nickname:'내퐁이',avatarPath:null,gold:100}]},receipt:{gold:100,xp:2,replayed:false}}))
 await waitFor(()=>expect(screen.queryByRole('dialog')).toBeNull())
 expect(screen.getByText('내퐁이')).toBeTruthy();expect(toast.success).toHaveBeenCalledWith('100골드를 보냈어요. 경험치 +2')
})
it('retries an uncertain transfer with the same ID even after the visible wallet balance decreases',async()=>{
 service.giveBegging.mockRejectedValueOnce(new Error('network')).mockResolvedValueOnce({request:{...post,receivedGold:100},receipt:{gold:100,xp:2,replayed:true}})
 const view=render(<BeggingScreen owner="me" gold={100} service={service}/>)
 fireEvent.click(await screen.findByRole('button',{name:/골드 보내기/}))
 fireEvent.click(within(screen.getByRole('dialog')).getByRole('button',{name:'100골드 보내기'}))
 await screen.findByRole('alert')
 view.rerender(<BeggingScreen owner="me" gold={0} service={service}/>)
 expect((screen.getByLabelText('보낼 골드') as HTMLInputElement).disabled).toBe(true)
 fireEvent.click(screen.getByRole('button',{name:'같은 송금 결과 확인'}))
 await waitFor(()=>expect(service.giveBegging).toHaveBeenCalledTimes(2))
 expect(service.giveBegging.mock.calls[1][0]).toEqual(service.giveBegging.mock.calls[0][0])
 await waitFor(()=>expect(screen.queryByRole('dialog')).toBeNull())
 expect(toast.success).toHaveBeenCalledWith('이미 완료된 송금이에요.')
})
it('posts a story and target amount and loads transfer history only when selected',async()=>{
 service.createBegging.mockResolvedValue({...post,mine:true})
 render(<BeggingScreen owner="me" gold={1000} service={service}/>)
 fireEvent.click(screen.getByRole('button',{name:'사연 쓰기'}))
 fireEvent.change(screen.getByLabelText('나의 사연'),{target:{value:'작은 어항이 필요해요.'}})
 fireEvent.change(screen.getByLabelText('목표 골드'),{target:{value:'2000'}})
 fireEvent.click(screen.getByRole('button',{name:'사연 등록하기'}))
 await waitFor(()=>expect(service.createBegging).toHaveBeenCalledWith({operationId:expect.any(String),story:'작은 어항이 필요해요.',goalGold:2000}))
 await waitFor(()=>expect(screen.queryByRole('dialog')).toBeNull())
 expect(service.loadBeggingHistory).not.toHaveBeenCalled()
 service.loadBeggingHistory.mockResolvedValue({items:[{id:'payment',requestId:'story',story:post.story,gold:100,xp:2,direction:'sent',createdAt:post.createdAt,person:{nickname:'낚시퐁이',avatarPath:null}}],hasMore:false})
 fireEvent.click(screen.getByRole('button',{name:'송금 기록',exact:true}))
 await screen.findByText('경험치 +2',{exact:true})
 expect(screen.getByText('−100골드')).toBeTruthy()
})
it('loads public contribution records on demand and confirms manual closure without deleting received gold',async()=>{
 service.loadBegging.mockResolvedValue({items:[{...post,mine:true,receivedGold:200}],hasMore:false})
 service.closeBegging.mockResolvedValue({...post,mine:true,receivedGold:200,status:'closed'})
 render(<BeggingScreen owner="owner" gold={1000} service={service}/>)
 fireEvent.click(await screen.findByRole('button',{name:'기록 보기'}))
 await waitFor(()=>expect(service.loadBeggingDetail).toHaveBeenCalledExactlyOnceWith('story',0))
 fireEvent.click(within(screen.getByRole('dialog')).getByRole('button',{name:'Close'}))
 fireEvent.click(screen.getByRole('button',{name:'마감하기'}))
 expect(service.closeBegging).not.toHaveBeenCalled()
 const confirm=screen.getByRole('alertdialog');expect(within(confirm).getByText(/이미 받은 골드는 그대로 유지/)).toBeTruthy()
 fireEvent.click(within(confirm).getByRole('button',{name:'마감하기'}))
 await screen.findByText('마감된 사연이에요.')
})
