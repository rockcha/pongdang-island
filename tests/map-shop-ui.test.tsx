vi.mock('@/features/collection/api',()=>({collectibleUrl:(path:string)=>'/collectibles/'+path}))
import {cleanup,fireEvent,render,screen,waitFor,within} from '@testing-library/react'
import {afterEach,expect,it,vi} from 'vitest'
import {MemoryRouter} from 'react-router'
import {ShopPage} from '@/features/gold/shop-page'
const mock=vi.hoisted(()=>({load:vi.fn(),trade:vi.fn(),bait:vi.fn()}))
vi.mock('@/features/gold/gold-provider',()=>({GoldIcon:()=>null,useGold:()=>({wallet:{gold:10000,inventory:{}},transact:mock.trade,batchEffects:async(work:()=>Promise<void>)=>work(),loading:false,busy:false,error:'',testEnabled:false,refresh:vi.fn()})}))
vi.mock('@/features/regions/map-shop-api',()=>({loadMapShop:mock.load}))
vi.mock('@/features/fishing/api',()=>({loadFishing:mock.bait}))
vi.mock('@/features/fishing/fishing-rod-ui',()=>({FishingRodShop:()=> <p>낚싯대 목록</p>}))
vi.mock('@/features/collection/collectible-thumbnail',()=>({CollectibleThumbnail:()=>null}))
afterEach(()=>{cleanup();vi.resetAllMocks()})
it('starts with bait and keeps maps in the item shop',()=>{
 mock.bait.mockResolvedValue({baits:[]})
 render(<MemoryRouter initialEntries={['/shop']}><ShopPage/></MemoryRouter>)
 expect(screen.getAllByRole('tab').map(tab=>tab.textContent)).toEqual(['미끼','낚싯대'])
 expect(screen.getByRole('tab',{name:'미끼'}).getAttribute('aria-selected')).toBe('true')
})
it('buys the selected bait quantity and releases the purchase lock afterwards',async()=>{
 mock.bait.mockResolvedValue({baits:[{id:'bait',name:'퐁당 지렁이',description:'미끼',price:30,effect_description:'효과',image_path:'bait.png'},{id:'free',name:'달빛 미끼',description:'미끼',price:null,effect_description:'효과',image_path:'free.png'}]})
 mock.trade.mockResolvedValue(undefined)
 render(<MemoryRouter initialEntries={['/shop?tab=bait']}><ShopPage/></MemoryRouter>)
 fireEvent.click(await screen.findByRole('button',{name:'퐁당 지렁이 상세 보기'}))
 fireEvent.click(screen.getByRole('button',{name:'구매 수량 늘리기'}))
 expect(screen.getByRole('button',{name:'퐁당 지렁이 2개 구매'}).textContent).toContain('60')
 fireEvent.click(screen.getByRole('button',{name:'퐁당 지렁이 2개 구매'}))
 await waitFor(()=>expect(mock.trade).toHaveBeenCalledTimes(2))
 await screen.findByRole('button',{name:'퐁당 지렁이 1개 구매'})
 fireEvent.click(screen.getByRole('button',{name:'퐁당 지렁이 1개 구매'}))
 await waitFor(()=>expect(mock.trade).toHaveBeenCalledTimes(3))
 await waitFor(()=>expect((screen.getByRole('button',{name:'퐁당 지렁이 1개 구매'}) as HTMLButtonElement).disabled).toBe(false))
 fireEvent.click(screen.getByRole('button',{name:'Close'}))
 fireEvent.click(screen.getByRole('button',{name:'달빛 미끼 상세 보기'}))
 expect(within(screen.getByRole('dialog')).getByText('구매 불가')).toBeTruthy()
 expect(screen.queryByRole('spinbutton')).toBeNull()
})
it('opens the map shop from its link and confirms a purchase without rarity or duplicate purchase',async()=>{
 mock.load.mockResolvedValue({items:[{region_id:'coral',name:'산호빛 여울 지도',description:'새 바다',price:500,thumbnail_path:'map.png',owned:false},{region_id:'primal',name:'태고의 원시섬 지도',description:'원시 바다',price:3000,thumbnail_path:'map2.png',owned:true}]})
 mock.trade.mockResolvedValue(undefined)
 render(<MemoryRouter initialEntries={['/item-shop?tab=maps']}><ShopPage items/></MemoryRouter>)
 expect(screen.getByRole('tab',{name:'기름'})).toBeTruthy()
 expect(screen.getByRole('tab',{name:'지도'}).getAttribute('aria-selected')).toBe('true')
 await screen.findByRole('article',{name:'산호빛 여울 지도'})
 expect(screen.getByText('더 비싼 지도에서는 같은 등급의 고유 생물이 평균적으로 더 높은 가치를 가져요.')).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'태고의 원시섬 지도 상세 보기'}))
 expect((screen.getByRole('button',{name:'태고의 원시섬 지도 보유중'}) as HTMLButtonElement).disabled).toBe(true)
 fireEvent.click(screen.getByRole('button',{name:'Close'}))
 fireEvent.click(screen.getByRole('button',{name:'산호빛 여울 지도 상세 보기'}))
 expect(screen.getByRole('button',{name:'산호빛 여울 지도 구매'}).textContent).toBe('500')
 fireEvent.click(screen.getByRole('button',{name:'산호빛 여울 지도 구매'}))
 const confirm=await screen.findByRole('alertdialog')
 fireEvent.click(within(confirm).getByRole('button',{name:'확인'}))
 await waitFor(()=>expect(mock.trade).toHaveBeenCalledWith({type:'buy',id:'map:coral',name:'산호빛 여울 지도'}))
 await waitFor(()=>expect(within(screen.getByRole('article',{name:'산호빛 여울 지도'})).getByText('보유중')).toBeTruthy())
 expect(screen.queryByText(/일반|희귀|특급|신화/)).toBeNull()
})
it('uses the actual fishing bait catalog instead of legacy shell merchandise',async()=>{
 mock.bait.mockResolvedValue({baits:[{id:'bait_safe',name:'안심 미끼',description:'안전해요',price:70,effect_description:'안정적인 미끼',image_path:'bait.png'}]})
 mock.trade.mockResolvedValue(undefined)
 render(<MemoryRouter initialEntries={['/shop?tab=bait']}><ShopPage/></MemoryRouter>)
 fireEvent.click(await screen.findByRole('button',{name:'안심 미끼 상세 보기'}))
 fireEvent.click(screen.getByRole('button',{name:'안심 미끼 1개 구매'}))
 await waitFor(()=>expect(mock.trade).toHaveBeenCalledWith({type:'buy',id:'fishing:bait_safe',name:'안심 미끼'}))
 expect(screen.queryByText('진주 조개')).toBeNull()
})

it('opens the linked region map detail after the catalog loads',async()=>{
 mock.load.mockResolvedValue({items:[{region_id:'coral',name:'산호빛 여울 지도',description:'새 바다',price:500,thumbnail_path:'map.png',owned:false}]})
 render(<MemoryRouter initialEntries={['/item-shop?tab=maps&region=coral']}><ShopPage items/></MemoryRouter>)
 expect(await screen.findByRole('dialog',{name:'산호빛 여울 지도'})).toBeTruthy()
 expect(screen.getByRole('button',{name:'산호빛 여울 지도 구매'})).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'Close'}))
 await waitFor(()=>expect(screen.queryByRole('dialog')).toBeNull())
})
