it('confirms consumption and sends one operation despite repeated taps',async()=>{
 let finish:(data:ReturnType<typeof sample>)=>void=()=>{}
 mocks.deliver.mockImplementation(()=>new Promise(resolve=>{finish=resolve}))
 render(<MerchantPage/>);fireEvent.click((await screen.findAllByRole('button',{name:'납품하기'}))[0])
 const dialog=screen.getByRole('dialog'),submit=within(dialog).getByRole('button',{name:'595골드 받고 납품'})
 expect(dialog.textContent).toContain('되돌릴 수 없어요')
 expect(within(dialog).getByText('일반 판매가')).toBeTruthy()
 expect(within(dialog).getByText('395골드')).toBeTruthy()
 fireEvent.change(within(dialog).getByRole('textbox',{name:'납품 한마디'}),{target:{value:'상인님, 잘 모아왔어요!'}})
 expect(mocks.deliver).not.toHaveBeenCalled()
 fireEvent.click(submit);fireEvent.click(submit)
 expect(mocks.deliver).toHaveBeenCalledOnce();expect(mocks.deliver.mock.calls[0][0]).toBe('1')
 expect(mocks.deliver.mock.calls[0][2]).toBe('상인님, 잘 모아왔어요!')
 finish({...sample(),receipt:{orderId:'1',gold:595},deliveredToday:1} as ReturnType<typeof sample>)
 await waitFor(()=>expect(screen.queryByRole('dialog')).toBeNull())
 expect(localStorage.getItem('pongdang:merchant:merchant-ui')).toBeNull()
 expect(mocks.refresh).not.toHaveBeenCalled()
})
