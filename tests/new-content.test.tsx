import { act, cleanup, renderHook, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { useNewContent } from '@/components/use-new-content'
const mock = vi.hoisted(() => ({ owner: 'me', path: '/', rpc: vi.fn(), allowed: true, auth: undefined as undefined | (() => void) }))
vi.mock('@/components/auth-provider', () => ({ useAuth: () => ({ session: { user: { id: mock.owner } }, recovery: false }) }))
vi.mock('react-router', () => ({ useLocation: () => ({ pathname: mock.path }) }))
vi.mock('@/lib/background-session', () => ({ hasBackgroundSession: async () => mock.allowed, isAuthFailure: (e: {code?:string}) => e.code === '42501' }))
vi.mock('@/lib/client', () => ({ createClient: () => ({ rpc: mock.rpc, auth: { onAuthStateChange: (callback: () => void) => {mock.auth=callback;return {data:{subscription:{unsubscribe:vi.fn()}}}} } }) }))
const timestamp = '2026-10-21T01:00:00Z'
const latest = { board: timestamp, exchange: timestamp, suggestions: null, bugs: null, showcase: timestamp }
beforeEach(() => { localStorage.clear(); vi.clearAllMocks(); mock.owner='me';mock.path='/';mock.allowed=true;mock.rpc.mockResolvedValue({data:{...latest},error:null}) })
afterEach(() => {cleanup();vi.useRealTimers()})
it('uses one timestamp request and marks visited feeds without refetching on navigation', async () => {
 const view=renderHook(()=>useNewContent())
 await waitFor(()=>expect(view.result.current.board).toBe(true))
 expect(mock.rpc).toHaveBeenCalledExactlyOnceWith('new_content_state')
 mock.path='/board';view.rerender()
 await waitFor(()=>expect(view.result.current.board).toBe(false))
 expect(view.result.current.exchange).toBe(true)
 mock.path='/showcase/preview';view.rerender()
 expect(view.result.current.showcase).toBe(true)
 mock.path='/showcase';view.rerender()
 await waitFor(()=>expect(view.result.current.showcase).toBe(false))
 expect(mock.rpc).toHaveBeenCalledTimes(1)
 mock.owner='other';view.rerender()
 await waitFor(()=>expect(view.result.current.board).toBe(true))
 expect(mock.rpc).toHaveBeenCalledTimes(2)
})
it('shows newer posts after visiting and preserves badges on a failed request',async()=>{
 mock.path='/board';const view=renderHook(()=>useNewContent())
 await waitFor(()=>expect(localStorage.getItem('pongdang:content-seen:me:board')).toBeTruthy())
 mock.path='/';view.rerender()
 mock.rpc.mockResolvedValue({data:{...latest,board:'2026-10-21T02:00:00Z'},error:null})
 act(()=>window.dispatchEvent(new Event('board-changed')))
 await waitFor(()=>expect(view.result.current.board).toBe(true))
 mock.rpc.mockResolvedValue({data:null,error:{code:'offline'}})
 act(()=>window.dispatchEvent(new Event('focus')))
 await waitFor(()=>expect(mock.rpc).toHaveBeenCalledTimes(3))
 expect(view.result.current.board).toBe(true)
})
it('stops requests after authorization failure until the SDK reports an auth change',async()=>{
 mock.rpc.mockResolvedValue({data:null,error:{code:'42501'}})
 renderHook(()=>useNewContent())
 await waitFor(()=>expect(mock.rpc).toHaveBeenCalledTimes(1))
 await act(async()=>{window.dispatchEvent(new Event('focus'));window.dispatchEvent(new Event('board-changed'))})
 expect(mock.rpc).toHaveBeenCalledTimes(1)
 mock.rpc.mockResolvedValue({data:latest,error:null})
 act(()=>mock.auth?.())
 await waitFor(()=>expect(mock.rpc).toHaveBeenCalledTimes(2))
})
it('never sends requests without a current SDK session',async()=>{
 mock.allowed=false;renderHook(()=>useNewContent())
 await act(async()=>{})
 expect(mock.rpc).not.toHaveBeenCalled()
})
