import {act,cleanup,renderHook,waitFor} from '@testing-library/react'
import {afterEach,beforeEach,expect,it,vi} from 'vitest'
import {useNewContent} from '@/components/use-new-content'
import {AppQueryProvider} from '@/lib/account-query'
import {appQueryClient,setQueryAccount} from '@/lib/account-cache'
import {markContentSeen} from '@/lib/content-seen'
const mock=vi.hoisted(()=>({owner:'me',path:'/',reply:vi.fn(),rpc:vi.fn(),allowed:true,auth:undefined as undefined|(()=>void)}))
vi.mock('@/components/auth-provider',()=>({useAuth:()=>({session:{user:{id:mock.owner}},recovery:false})}))
vi.mock('react-router',()=>({useLocation:()=>({pathname:mock.path})}))
vi.mock('@/lib/background-session',()=>({hasBackgroundSession:async()=>mock.allowed,isAuthFailure:(e:{code?:string}|null)=>e?.code==='42501'}))
vi.mock('@/lib/client',()=>({createClient:()=>({rpc:mock.rpc,auth:{onAuthStateChange:(callback:()=>void)=>{mock.auth=callback;return {data:{subscription:{unsubscribe:vi.fn()}}}}}})}))
const timestamp='2026-10-21T01:00:00Z'
const latest={board:timestamp,exchange:timestamp,flea:timestamp,suggestions:null,bugs:null,showcase:timestamp,merchant:null}
const setup=()=>renderHook(()=>useNewContent(),{wrapper:AppQueryProvider})
beforeEach(()=>{localStorage.clear();vi.clearAllMocks();appQueryClient.clear();mock.owner='me';mock.path='/';mock.allowed=true;setQueryAccount('me');mock.reply.mockResolvedValue({data:{...latest},error:null});mock.rpc.mockImplementation(()=>({abortSignal:mock.reply}))})
afterEach(()=>{cleanup();appQueryClient.clear();setQueryAccount(null);vi.useRealTimers()})

it('shares timestamps across consumers and marks visited feeds without navigation requests',async()=>{
 const view=setup(),second=setup()
 await waitFor(()=>expect(view.result.current.board).toBe(true))
 expect(second.result.current.flea).toBe(true)
 expect(mock.rpc).toHaveBeenCalledExactlyOnceWith('new_content_state')
 expect(mock.reply.mock.calls[0][0]).toBeInstanceOf(AbortSignal)
 mock.path='/board';view.rerender();second.rerender()
 expect(view.result.current.board).toBe(false)
 expect(view.result.current.exchange).toBe(true)
 mock.path='/showcase/preview';view.rerender()
 expect(view.result.current.showcase).toBe(true)
 mock.path='/showcase';view.rerender()
 expect(view.result.current.showcase).toBe(false)
 expect(mock.rpc).toHaveBeenCalledTimes(1)
})
it('clears flea NEW on visiting and announces a newer sell or buy post after leaving',async()=>{
 const view=setup()
 await waitFor(()=>expect(view.result.current.flea).toBe(true))
 mock.path='/flea-market';view.rerender()
 expect(view.result.current.flea).toBe(false)
 expect(localStorage.getItem('pongdang:content-seen:me:flea')).toBe(String(Date.parse(timestamp)))
 mock.path='/';view.rerender()
 expect(view.result.current.flea).toBe(false)
 mock.reply.mockResolvedValue({data:{...latest,flea:'2026-10-21T02:00:00Z'},error:null})
 act(()=>window.dispatchEvent(new Event('focus')))
 await waitFor(()=>expect(view.result.current.flea).toBe(true))
 mock.reply.mockResolvedValue({data:null,error:{code:'offline'}})
 act(()=>window.dispatchEvent(new Event('focus')))
 await waitFor(()=>expect(mock.rpc).toHaveBeenCalledTimes(3))
 expect(view.result.current.flea).toBe(true)
})
it('keeps merchant visitation distinct from new day timestamps',async()=>{
 mock.reply.mockResolvedValue({data:{...latest,merchant:timestamp},error:null})
 const view=setup()
 await waitFor(()=>expect(view.result.current.merchant).toBe(true))
 mock.path='/merchant-orders';view.rerender()
 expect(view.result.current.merchant).toBe(false)
 mock.path='/';view.rerender()
 expect(view.result.current.merchant).toBe(false)
 mock.reply.mockResolvedValue({data:{...latest,merchant:'2026-10-22T01:00:00Z'},error:null})
 act(()=>window.dispatchEvent(new Event('focus')))
 await waitFor(()=>expect(view.result.current.merchant).toBe(true))
})
it('stops polling after auth failure and resumes when SDK auth changes',async()=>{
 mock.reply.mockResolvedValue({data:null,error:{code:'42501'}})
 const view=setup()
 await waitFor(()=>expect(mock.rpc).toHaveBeenCalledTimes(1))
 await act(async()=>{})
 await act(async()=>{window.dispatchEvent(new Event('focus'));window.dispatchEvent(new Event('board-changed'))})
 expect(mock.rpc).toHaveBeenCalledTimes(1)
 mock.reply.mockResolvedValue({data:latest,error:null})
 act(()=>mock.auth?.())
 await waitFor(()=>expect(view.result.current.flea).toBe(true))
 expect(mock.rpc).toHaveBeenCalledTimes(2)
})
it('never sends requests without a current SDK session',async()=>{
 mock.allowed=false;setup()
 await act(async()=>{})
 expect(mock.rpc).not.toHaveBeenCalled()
})
it('does not apply a late old-account response or carry over its seen markers',async()=>{
 let finish!:(value:unknown)=>void
 mock.reply.mockImplementationOnce(()=>new Promise(resolve=>{finish=resolve}))
 const view=setup()
 await waitFor(()=>expect(mock.rpc).toHaveBeenCalledTimes(1))
 act(()=>{mock.owner='other';setQueryAccount('other');view.rerender()})
 await waitFor(()=>expect(view.result.current.flea).toBe(true))
 await act(async()=>finish({data:{...latest,flea:'2099-01-01T00:00:00Z'},error:null}))
 mock.path='/flea-market';view.rerender()
 expect(localStorage.getItem('pongdang:content-seen:other:flea')).toBe(String(Date.parse(timestamp)))
 expect(localStorage.getItem('pongdang:content-seen:me:flea')).toBeNull()
})
it('syncs another tab seen marker without a new RPC',async()=>{
 const view=setup()
 await waitFor(()=>expect(view.result.current.flea).toBe(true))
 const key='pongdang:content-seen:me:flea'
 localStorage.setItem(key,String(Date.parse(timestamp)))
 act(()=>window.dispatchEvent(new StorageEvent('storage',{key})))
 expect(view.result.current.flea).toBe(false)
 expect(mock.rpc).toHaveBeenCalledTimes(1)
})
it('checks new posts through the shared minute poll without navigating',async()=>{
 vi.useFakeTimers()
 mock.path='/flea-market'
 const view=setup()
 await act(async()=>{await vi.advanceTimersByTimeAsync(1)})
 expect(mock.rpc).toHaveBeenCalledTimes(1)
 mock.path='/';view.rerender()
 expect(view.result.current.flea).toBe(false)
 mock.reply.mockResolvedValue({data:{...latest,flea:'2026-10-21T02:00:00Z'},error:null})
 await act(async()=>{await vi.advanceTimersByTimeAsync(60_000)})
 expect(view.result.current.flea).toBe(true)
 expect(mock.rpc).toHaveBeenCalledTimes(2)
})

it.each([['bugs','/square/bugs'],['suggestions','/square/suggestions']] as const)('keeps already loaded %s seen when an older menu cache catches up',async(source,path)=>{
 const loaded='2026-10-21T02:00:00Z',newer='2026-10-21T03:00:00Z'
 mock.reply.mockResolvedValue({data:{...latest,[source]:timestamp},error:null})
 const view=setup(),second=setup()
 await waitFor(()=>expect(view.result.current[source]).toBe(true))
 mock.path=path;view.rerender();second.rerender()
 expect(localStorage.getItem('pongdang:content-seen:me:'+source)).toBeNull()
 act(()=>markContentSeen('me',source,[loaded]))
 mock.path='/';view.rerender();second.rerender()
 expect(view.result.current[source]).toBe(false);expect(second.result.current[source]).toBe(false)
 mock.reply.mockResolvedValue({data:{...latest,[source]:loaded},error:null})
 act(()=>window.dispatchEvent(new Event('focus')))
 await waitFor(()=>expect(mock.rpc).toHaveBeenCalledTimes(2))
 expect(view.result.current[source]).toBe(false)
 mock.path=path;view.rerender()
 mock.reply.mockResolvedValue({data:{...latest,[source]:newer},error:null})
 act(()=>window.dispatchEvent(new Event('focus')))
 await waitFor(()=>expect(appQueryClient.getQueryData<{[key:string]:string}>(['account','me','new-content'])?.[source]).toBe(newer))
 // A menu poll while on the page must not acknowledge posts absent from its loaded feed.
 mock.path='/';view.rerender()
 expect(view.result.current[source]).toBe(true)
 act(()=>markContentSeen('me',source,[timestamp]))
 expect(localStorage.getItem('pongdang:content-seen:me:'+source)).toBe(String(Date.parse(loaded)))
})
