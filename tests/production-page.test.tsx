 expect(screen.getByRole('article').getAttribute('aria-label')).toBe(facilities[1].name)
 fireEvent.keyDown(screen.getByRole('tab',{name:'가동 중 1'}),{key:'ArrowRight'})
 expect(screen.getByRole('tab',{name:'수령 대기 1'}).getAttribute('aria-selected')).toBe('true')
