import {cleanup,fireEvent,render,screen,waitFor,within} from '@testing-library/react'
import {MemoryRouter} from 'react-router'
import {afterEach,beforeEach,expect,it,vi} from 'vitest'
import {ProductionPage} from '@/features/production/production-page'
import catalog from '../supabase/catalog/catalog.json'
const mock=vi.hoisted(()=>({load:vi.fn(),materials:vi.fn(),action:vi.fn()}))
vi.mock('@/features/production/api',async importOriginal=>({...await importOriginal<any>(),loadProduction:mock.load,loadProductionMaterials:mock.materials,actProduction:mock.action}))
vi.mock('@/features/collection/api',()=>({collectibleUrl:(path:string)=>'/test/'+path}))
const make=()=>({serverNow:new Date().toISOString(),gold:10000,fuel:3,facilities:catalog.production_facilities.map(f=>({...f,owned:false,startedAt:null,completesAt:null,expiresAt:null,runOutput:null}))})
beforeEach(()=>{mock.load.mockReset().mockResolvedValue(make());mock.materials.mockReset().mockResolvedValue([{id:'wood',name:'폐목재',thumbnail_path:'wood.png',rarity:'common',sell_price:2,available:10}]);mock.action.mockReset().mockResolvedValue(make())})
afterEach(cleanup)
it('opens the exact owned facility linked from the island without starting production',async()=>{
 const data=make(),facility={...data.facilities[0],owned:true,siteId:'island-fuel-site'}
 mock.load.mockResolvedValue({...data,sites:[facility]})
 render(<MemoryRouter initialEntries={['/production?site=island-fuel-site']}><ProductionPage/></MemoryRouter>)
 const dialog=await screen.findByRole('dialog')
 expect(dialog.textContent).toContain(facility.name)
 expect(mock.action).not.toHaveBeenCalled()
})
it('allows another purchase even when four facilities are already owned',async()=>{
 const data=make();Object.assign(data.facilities.find(f=>f.id==='tin-grandpa-hearth')!,{owned:true,ownedCount:4});mock.load.mockResolvedValue(data)
 render(<MemoryRouter><ProductionPage shop/></MemoryRouter>)
 fireEvent.click(await screen.findByRole('button',{name:'조개탄 미니가마 상세 보기'}))
 expect(screen.getByRole('button',{name:'350골드로 구매'}).hasAttribute('disabled')).toBe(false)
 expect(screen.getByRole('button',{name:'구매 수량 늘리기'}).hasAttribute('disabled')).toBe(false)
 expect(mock.action).not.toHaveBeenCalled()
})
it('requires confirmation to sell an idle facility for half its shop price',async()=>{
 const data=make();data.facilities.find(f=>f.id==='tin-grandpa-hearth')!.owned=true;mock.load.mockResolvedValue(data)
 render(<MemoryRouter><ProductionPage/></MemoryRouter>)
 fireEvent.click(await screen.findByRole('button',{name:'깡통 할아범의 화덕 정보'}))
 fireEvent.click(screen.getByRole('button',{name:'판매 400골드'}))
 expect(mock.action).not.toHaveBeenCalled()
 fireEvent.click(screen.getByRole('button',{name:'판매 확정'}))
 await waitFor(()=>expect(mock.action).toHaveBeenCalledWith(expect.objectContaining({p_action:'sell',p_facility:'tin-grandpa-hearth',p_operation_id:expect.any(String)})))
})
it('buys through a confirmation and updates the purchased facility',async()=>{
 const result=make();result.facilities.find(f=>f.id==='shell-coal-mini-kiln')!.owned=true;result.gold=9650;mock.action.mockResolvedValue(result)
 render(<MemoryRouter><ProductionPage shop/></MemoryRouter>)
 fireEvent.click(await screen.findByRole('button',{name:'조개탄 미니가마 상세 보기'}))
 fireEvent.click(screen.getByRole('button',{name:'350골드로 구매'}))
 await waitFor(()=>expect(mock.action).toHaveBeenCalledWith(expect.objectContaining({p_action:'buy',p_facility:'shell-coal-mini-kiln',p_operation_id:expect.any(String)})))
 expect(await screen.findByText('보유 1곳')).toBeTruthy()
 expect(screen.getByRole('button',{name:'조개탄 미니가마 상세 보기'})).toBeTruthy()
})
it('shows only owned facilities and selects enough materials before starting',async()=>{
 const data=make();data.facilities.find(f=>f.id==='tin-grandpa-hearth')!.owned=true;mock.load.mockResolvedValue(data)
 render(<MemoryRouter><ProductionPage/></MemoryRouter>)
 fireEvent.click(await screen.findByRole('button',{name:'깡통 할아범의 화덕 · 가동 대기'}))
 const start=await screen.findByRole('button',{name:'재료 넣고 가동하기'})
 expect(start.hasAttribute('disabled')).toBe(true)
 await screen.findByText('폐목재')
 fireEvent.click(screen.getByRole('button',{name:'자동 넣기'}))
 await waitFor(()=>expect(start.hasAttribute('disabled')).toBe(false))
 expect(within(screen.getByRole('dialog')).queryByText('생산량')).toBeNull()
 expect(within(screen.getByRole('dialog')).queryByText('보관 기간')).toBeNull()
 fireEvent.click(screen.getByRole('button',{name:'폐목재 선택한 재료 1개 빼기'}))
 expect(screen.getByRole('progressbar',{name:'넣은 재료'}).getAttribute('aria-valuenow')).toBe('2')
 expect(start.hasAttribute('disabled')).toBe(true)
 fireEvent.click(screen.getByRole('button',{name:'폐목재 선택한 재료 1개 빼기'}))
 fireEvent.click(screen.getByRole('button',{name:'폐목재 선택한 재료 1개 빼기'}))
 expect(screen.queryByRole('button',{name:'폐목재 선택한 재료 1개 빼기'})).toBeNull()
 expect(screen.getByRole('progressbar',{name:'넣은 재료'}).getAttribute('aria-valuenow')).toBe('0')
 fireEvent.click(screen.getByRole('button',{name:'자동 넣기'}))
 fireEvent.click(start)
 await waitFor(()=>expect(mock.action).toHaveBeenCalledWith(expect.objectContaining({p_action:'start',p_materials:{wood:3}})))
})
