import {cleanup,fireEvent,render,screen,within,waitFor} from '@testing-library/react'
import {afterEach,expect,it,vi} from 'vitest'
import {RelicLoadout,RelicPage} from '@/features/relics/relic-loadout'
const {load,equip,sell,equipSound,unequipSound}=vi.hoisted(()=>({load:vi.fn(),equip:vi.fn(),sell:vi.fn(),equipSound:vi.fn(),unequipSound:vi.fn()}))
vi.mock('@/features/gold/purchase-sound',()=>({playRelicEquipSound:equipSound,playRelicUnequipSound:unequipSound}))
vi.mock('@/features/relics/api',()=>({loadRelics:load,equipRelic:equip,sellRelic:sell,relicError:()=> '다시 확인해 주세요.'}))
vi.mock('@/components/auth-provider',()=>({useAuth:()=>({session:{user:{id:'relic-test'}}})}))
vi.mock('@/features/gold/gold-provider',()=>({GoldIcon:()=>null}))
vi.mock('@/features/collection/collectible-thumbnail',()=>({CollectibleThumbnail:({name}:{name:string})=><span role="img" aria-label={name}/>}))
const a={id:'a',name:'조개 모래시계',description:'최대 제작 시간 +2시간',rarity:'rare',thumbnail_path:'a.png',owned:true,sell_price:200,effect_kind:'personal_bait_hours',effect_value:2}
const b={...a,id:'b',name:'영원의 물시계',rarity:'mythic',owned:false,effect_value:8}
const state={equippedId:null,changeFee:500,equipFee:0,unequipFee:500,relics:[a,b]}
afterEach(()=>{cleanup();localStorage.clear();vi.clearAllMocks()})
it('filters relics through the shared ownership tabs',async()=>{
 load.mockResolvedValue(state);render(<RelicPage/>)
 await screen.findByRole('article',{name:a.name})
 expect(screen.getByRole('heading',{name:'나의 유물 슬롯'}).querySelector('img')).toBeNull()
 fireEvent.click(screen.getByRole('tab',{name:'보유 1'}))
 await screen.findByRole('article',{name:a.name});expect(screen.queryByRole('article',{name:b.name})).toBeNull()
 fireEvent.click(screen.getByRole('tab',{name:'미보유 1'}))
 await screen.findByRole('article',{name:b.name});expect(screen.queryByRole('article',{name:a.name})).toBeNull()
 fireEvent.click(screen.getByRole('tab',{name:'전체 2'}))
 expect(await screen.findAllByRole('article')).toHaveLength(2)
})
it('pins the equipped artwork and clean effect above the relic collection',async()=>{
 load.mockResolvedValue({...state,equippedId:'a',relics:[{...a,description:'최대 제작 시간 +2시간 · 장착 중에만 효과가 적용돼요.'},b]})
 render(<RelicPage/>)
 const slot=await screen.findByRole('region',{name:'장착 슬롯'})
 await within(slot).findByText(a.name)
 expect(within(slot).getByRole('img',{name:`장착 중: ${a.name}`})).toBeTruthy()
 expect(within(slot).getByText(/최대 제작 시간 \+2시간/)).toBeTruthy()
 expect(screen.queryByText(/장착 중에만/)).toBeNull()
 expect(within(slot).getByRole('button',{name:'해제'})).toBeTruthy()
 expect(screen.getByRole('tablist',{name:'유물 목록'})).toBeTruthy()
})
it('confirms sale proceeds and retries an uncertain sale with the same operation',async()=>{
 load.mockResolvedValue(state)
 sell.mockRejectedValueOnce(new Error('network')).mockResolvedValue({...state,relics:[{...a,owned:false,discovered:true},b]})
 render(<RelicPage/>)
 fireEvent.click(within(await screen.findByRole('article',{name:a.name})).getByRole('button',{name:'판매 200 골드'}))
 expect(sell).not.toHaveBeenCalled();expect(screen.getByRole('alertdialog').textContent).toContain('다시 만날 수 있어요')
 fireEvent.click(within(screen.getByRole('alertdialog')).getByRole('button',{name:'판매하기'}))
 await screen.findByRole('alert')
 fireEvent.click(within(screen.getByRole('alertdialog')).getByRole('button',{name:'결과 다시 확인'}))
 await waitFor(()=>expect(sell).toHaveBeenCalledTimes(2));expect(sell.mock.calls[0]).toEqual(sell.mock.calls[1])
 expect(sell.mock.calls[0]).toEqual(['a',expect.any(String),200])
 await waitFor(()=>expect(screen.queryByRole('alertdialog')).toBeNull())
 expect(within(screen.getByRole('article',{name:a.name})).getByRole('button',{name:'미보유'})).toHaveProperty('disabled',true)
})
it('loads the relic page directly and equips for free and charges 500 only for unequipping',async()=>{
 load.mockResolvedValue(state)
 equip.mockResolvedValueOnce({...state,equippedId:'a'}).mockResolvedValueOnce(state)
 render(<RelicPage/>)
 expect(screen.getByRole('region',{name:'유물'})).toBeTruthy()
 expect(screen.queryByRole('dialog')).toBeNull()
 fireEvent.click(within(await screen.findByRole('article',{name:a.name})).getByRole('button',{name:'장착'}))
 let confirm=screen.getByRole('alertdialog')
 expect(confirm.textContent).toContain('무료')
 fireEvent.click(within(confirm).getByRole('button',{name:'확인'}))
 await waitFor(()=>expect(screen.queryByRole('alertdialog')).toBeNull())
 expect(equip).toHaveBeenNthCalledWith(1,'a',expect.any(String),0)
 expect(equipSound).toHaveBeenCalledWith(equip.mock.calls[0][1]);expect(unequipSound).not.toHaveBeenCalled()
 fireEvent.click(screen.getByRole('button',{name:'해제'}))
 confirm=screen.getByRole('alertdialog')
 expect(within(confirm).getByRole('img',{name:'500 골드'})).toBeTruthy()
 fireEvent.click(within(confirm).getByRole('button',{name:'확인'}))
 await waitFor(()=>expect(screen.queryByRole('alertdialog')).toBeNull())
 expect(equip).toHaveBeenNthCalledWith(2,null,expect.any(String),500)
 expect(unequipSound).toHaveBeenCalledWith(equip.mock.calls[1][1])
 expect(screen.getByText('장착 중인 유물이 없어요.')).toBeTruthy()
})
