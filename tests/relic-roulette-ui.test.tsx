vi.mock('@/features/relic-roulette/wheel-scene',()=>({mountRelicWheel:()=>({spin:mocks.turn,destroy:mocks.destroy})}))
vi.mock('@/features/gold/purchase-sound',()=>({playRelicResultSound:mocks.sound}))
