it('restores an uncertain ticket purchase and retries the same ID despite the already-debited balance',async()=>{
 const view=mount();await ready()
 fireEvent.click(screen.getByRole('button',{name:'이용권 구매'}))
 mocks.rpc.mockRejectedValueOnce(Error('lost response'))
 fireEvent.click(screen.getByRole('button',{name:'5장 구매하기'}))
 await waitFor(()=>expect(screen.getByRole('button',{name:'같은 구매 다시 확인'})).toHaveProperty('disabled',false))
 const first=mocks.rpc.mock.calls.find(call=>call[0]==='relic_roulette_buy_tickets')![1]
 view.unmount();mount({...initial,gold:500,tickets:5})
 await waitFor(()=>expect(screen.getByRole('button',{name:'같은 구매 다시 확인'})).toHaveProperty('disabled',false))
 expect(screen.getByLabelText('구매 수량')).toHaveProperty('disabled',true)
 mocks.rpc.mockResolvedValueOnce({data:{...initial,gold:500,tickets:5,purchase:{operationId:first.p_operation_id,quantity:5,totalGold:2500},replayed:true},error:null})
 fireEvent.click(screen.getByRole('button',{name:'같은 구매 다시 확인'}))
 await waitFor(()=>expect(screen.queryByRole('dialog')).toBeNull())
 const calls=mocks.rpc.mock.calls.filter(call=>call[0]==='relic_roulette_buy_tickets')
 expect(calls).toHaveLength(2);expect(calls[1][1]).toEqual(first)
 expect(screen.getByLabelText('보유 이용권').textContent).toBe('5장')
})
