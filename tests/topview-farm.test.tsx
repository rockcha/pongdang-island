import {cleanup,fireEvent,render,screen,within} from '@testing-library/react'
import {MemoryRouter} from 'react-router'
import {afterEach,expect,it} from 'vitest'
import {TopviewFarm} from '@/features/farm/topview-farm'
import {buyTestLand,coastline,initialTopview,placementValid} from '@/features/farm/topview-model'
afterEach(cleanup)
it('only draws shore against water and reconnects it when new land is purchased',()=>{
 expect(coastline(['4,4'])).toHaveLength(4)
 const shore=coastline(['4,4','5,4'])
 expect(shore).toHaveLength(6)
 expect(shore.filter(edge=>edge.path==='M200 160V200')).toHaveLength(0)
 const initial=initialTopview(),bought=buyTestLand(initial,3,4)
 expect(coastline(bought.land)).toHaveLength(coastline(initial.land).length+2)
})
it('only buys adjacent land once and never spends beyond the test balance',()=>{
 const original=initialTopview()
 expect(buyTestLand(original,0,0)).toBe(original)
 const bought=buyTestLand(original,3,4)
 expect(bought.gold).toBe(original.gold-50)
 expect(buyTestLand(bought,3,4)).toBe(bought)
 const poor={...original,gold:49}
 expect(buyTestLand(poor,3,4)).toBe(poor)
 expect(original.land).not.toContain('3,4')
})
it('checks the complete rectangular footprint and excludes the object being moved',()=>{
 const state=initialTopview()
 expect(placementValid(state,'barn',18,14)).toBe(false)
 expect(placementValid(state,'office',6,5)).toBe(false)
 expect(placementValid(state,'office',6,5,1)).toBe(true)
 expect(placementValid(state,'chicken',6,9)).toBe(true)
})
it('offers land purchase in the current farm with an explicitly simulated balance',()=>{
 render(<MemoryRouter><TopviewFarm/></MemoryRouter>)
 expect(screen.getByText(/실제 골드 사용 없음/)).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'편집',exact:true}))
 fireEvent.click(screen.getByRole('button',{name:'땅 구매',exact:true}))
 fireEvent.click(screen.getByRole('button',{name:'땅 3,4 구매'}))
 expect(screen.getByRole('button',{name:'테스트 골드 안내'}).textContent).toContain('14,950')
 expect(screen.queryByRole('button',{name:'땅 3,4 구매'})).toBeNull()
 expect(screen.getByRole('button',{name:'땅 2,4 구매'})).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'한 단계 되돌리기'}))
 expect(screen.getByRole('button',{name:'테스트 골드 안내'}).textContent).toContain('15,000')
 fireEvent.click(screen.getByRole('button',{name:'땅 구매',exact:true}))
 expect(screen.getByRole('button',{name:'땅 3,4 구매'})).toBeTruthy()
 expect(screen.getByRole('button',{name:'한 단계 되돌리기'})).toHaveProperty('disabled',true)
})
it('recovers placed objects locally and resets to the original test layout',()=>{
 render(<MemoryRouter><TopviewFarm/></MemoryRouter>)
 fireEvent.click(screen.getByRole('button',{name:'편집',exact:true}))
 fireEvent.click(screen.getByRole('button',{name:'젖소 (16,9)'}))
 fireEvent.click(within(screen.getByRole('group',{name:'젖소 편집 메뉴'})).getByRole('button',{name:'회수'}))
 expect(screen.queryByRole('button',{name:'젖소 (16,9)'})).toBeNull()
 fireEvent.click(screen.getByRole('button',{name:'테스트 초기화'}))
 expect(screen.getByRole('button',{name:'젖소 (16,9)'})).toBeTruthy()
})
it('only exposes editing tools during editing and clears destructive tools on completion',()=>{
 render(<MemoryRouter><TopviewFarm/></MemoryRouter>)
 expect(screen.queryByRole('navigation',{name:'농장 편집 도구'})).toBeNull()
 expect(screen.queryByRole('button',{name:'격자 표시'})).toBeNull()
 expect(screen.queryByRole('button',{name:'테스트 초기화'})).toBeNull()
 fireEvent.click(screen.getByRole('button',{name:'편집',exact:true}))
 expect(screen.getByRole('button',{name:'격자 표시'}).getAttribute('aria-pressed')).toBe('true')
 fireEvent.click(screen.getByRole('button',{name:'젖소 (16,9)'}))
 expect(screen.getByRole('group',{name:'젖소 편집 메뉴'})).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'완료',exact:true}))
 expect(screen.queryByRole('navigation',{name:'농장 편집 도구'})).toBeNull()
 expect(screen.queryByRole('button',{name:'격자 표시'})).toBeNull()
 expect(screen.queryByRole('group',{name:'젖소 편집 메뉴'})).toBeNull()
 fireEvent.click(screen.getByRole('button',{name:'젖소 (16,9)'}))
 expect(screen.getByRole('dialog',{name:'젖소'})).toBeTruthy()
 expect(screen.getByRole('button',{name:'젖소 (16,9)',hidden:true})).toBeTruthy()
})
it('undoes multiple recoveries in reverse order',()=>{
 render(<MemoryRouter><TopviewFarm/></MemoryRouter>)
 fireEvent.click(screen.getByRole('button',{name:'편집',exact:true}))
 fireEvent.click(screen.getByRole('button',{name:'젖소 (16,9)'}))
 fireEvent.click(screen.getByRole('button',{name:'회수',exact:true}))
 fireEvent.click(screen.getByRole('button',{name:'닭 (14,10)'}))
 fireEvent.click(screen.getByRole('button',{name:'회수',exact:true}))
 fireEvent.click(screen.getByRole('button',{name:'한 단계 되돌리기'}))
 expect(screen.queryByRole('button',{name:'젖소 (16,9)'})).toBeNull()
 expect(screen.getByRole('button',{name:'닭 (14,10)'})).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'한 단계 되돌리기'}))
 expect(screen.getByRole('button',{name:'젖소 (16,9)'})).toBeTruthy()
})
it('previews moves without changing the layout, rejects occupied cells and supports cancel',()=>{
 render(<MemoryRouter><TopviewFarm/></MemoryRouter>)
 fireEvent.click(screen.getByRole('button',{name:'편집',exact:true}))
 const toolbar=screen.getByRole('navigation',{name:'농장 편집 도구'})
 expect(within(toolbar).queryByRole('button',{name:'이동'})).toBeNull()
 expect(within(toolbar).queryByRole('button',{name:'회수'})).toBeNull()
 fireEvent.click(screen.getByRole('button',{name:'젖소 (16,9)'}))
 fireEvent.click(screen.getByRole('button',{name:'이동',exact:true}))
 fireEvent.click(screen.getByRole('button',{name:'외양간 (15,5)'}))
 expect(screen.getByRole('button',{name:'배치',exact:true})).toHaveProperty('disabled',true)
 fireEvent.click(screen.getByRole('button',{name:'배치 위치 6,9'}))
 expect(screen.getByRole('button',{name:'젖소 (16,9)'})).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'취소',exact:true}))
 expect(screen.getByRole('button',{name:'젖소 (16,9)'})).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'이동',exact:true}))
 fireEvent.click(screen.getByRole('button',{name:'배치 위치 6,9'}))
 fireEvent.click(screen.getByRole('button',{name:'배치',exact:true}))
 expect(screen.queryByRole('button',{name:'젖소 (16,9)'})).toBeNull()
 expect(screen.getByRole('button',{name:'젖소 (6,9)'})).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'한 단계 되돌리기'}))
 expect(screen.getByRole('button',{name:'젖소 (16,9)'})).toBeTruthy()
})
it('stores recovered objects and places them again without charging gold',()=>{
 const {container}=render(<MemoryRouter><TopviewFarm/></MemoryRouter>)
 fireEvent.click(screen.getByRole('button',{name:'편집',exact:true}))
 fireEvent.click(screen.getByRole('button',{name:'젖소 (16,9)'}))
 fireEvent.click(screen.getByRole('button',{name:'회수',exact:true}))
 expect(screen.getByRole('status').textContent).toContain('젖소 회수 완료')
 fireEvent.click(screen.getByRole('button',{name:'보관함',exact:true}))
 fireEvent.click(screen.getByRole('button',{name:/젖소.*보관 1개 · 무료/}))
 fireEvent.click(container.querySelector('[data-farm-cell="6,9"]')!)
 expect(screen.getByRole('button',{name:'젖소 (6,9)'})).toBeTruthy()
 expect(screen.getByRole('button',{name:'테스트 골드 안내'}).textContent).toContain('15,000')
 expect(screen.getByText('회수한 개체가 여기에 보관돼요.')).toBeTruthy()
 fireEvent.click(container.querySelector('[data-farm-cell="7,13"]')!)
 expect(screen.queryByRole('button',{name:'젖소 (7,13)'})).toBeNull()
 expect(screen.getByRole('button',{name:'테스트 골드 안내'}).textContent).toContain('15,000')
})
